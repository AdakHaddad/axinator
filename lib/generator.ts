function generateRegMapMd(cfg: IPConfig): string {
  const physRegs = countPhysicalRegs(cfg.registers);
  const addrWidth = calcAddrWidth(physRegs);

  // De-duplicate rows by address for the table header, show all entries (packed ports each get a row)
  const rows = cfg.registers.map(r =>
    `| ${formatAddress(r.address)} | ${r.regName}[${r.msb}:${r.lsb}] | ${r.mappedPort} | ${r.width} | ${r.mode} |`
  ).join('\n');

  return `# Register Map: ${cfg.ipName}

| Address | Register Slice | Mapped Port | Width | Mode |
|---------|---------------|-------------|-------|------|
${rows || '| — | — | No AXI registers configured | — | — |'}

## Notes
- Packed pairs: two ports with width ≤ 16 share one 32-bit register word.
  Low half [15:0] = first port, high half [31:16] = second port.

## Address Width
\`C_S_AXI_ADDR_WIDTH = ${addrWidth}\`

## AXI Access Example (C pseudocode)
\`\`\`c
#define BASE_ADDR  0x43C00000  // example Zynq AXI GP base

${cfg.registers.map(r =>
  `// ${r.mappedPort} → ${r.regName}[${r.msb}:${r.lsb}]\n*(volatile uint32_t*)(BASE_ADDR + ${formatAddress(r.address)}) = value;`
).join('\n') || '// No registers configured'}
\`\`\`
`;
}

// ─────────────────────────────────────────────────────────────────────────────
// C driver (.h + .c)
// Gives firmware a typed, register-map-aware API so the IP is controllable
// from C out of the box (e.g. MicroBlaze / Zynq / RISC-V soft-core).
// ─────────────────────────────────────────────────────────────────────────────

function cIdent(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_').toUpperCase();
}

function generateDriverHeader(cfg: IPConfig): string {
  const up = cIdent(cfg.ipName);
  const portRow =
    (r: RegisterEntry) =>
      `/* ${r.mappedPort} -> ${r.regName}[${r.msb}:${r.lsb}] (${r.width} bit, ${r.mode}) */`;

  const accessors = cfg.registers
    .filter(r => r.mode !== 'RO')
    .map(r => {
      const fn = `${cfg.ipName}_set_${r.mappedPort}`;
      const argType = r.width <= 32 && r.width > 16 ? 'uint32_t' : 'uint32_t';
      return `${portRow(r)}\nvoid ${fn}(${argType} value);`;
    }).join('\n');

  const readers = cfg.registers
    .filter(r => r.mode !== 'WO')
    .map(r => {
      const fn = `${cfg.ipName}_get_${r.mappedPort}`;
      return `${portRow(r)}\nuint32_t ${fn}(void);`;
    }).join('\n');

  return `/** ${cfg.ipName} — autogenerated C driver.
 * Peripheral base address is an example; redefine ${up}_BASE at build time
 * (or override in the Makefile / linker script) with the value Vivado assigns
 * in the address map (see the block design address editor).
 */
#ifndef ${up}_DRIVER_H
#define ${up}_DRIVER_H

#include <stdint.h>

#ifndef ${up}_BASE
#define ${up}_BASE 0x43C00000U
#endif

/* --- Register offset access --- */
uint32_t ${cfg.ipName}_read(uint32_t offset);
void     ${cfg.ipName}_write(uint32_t offset, uint32_t value);

/* --- Per-port accessors (register-slice aware; packed-word RMW handled) --- */
${accessors}
${readers}

#endif /* ${up}_DRIVER_H */
`;
}

function generateDriverSource(cfg: IPConfig): string {
  const up = cIdent(cfg.ipName);
  const regConsts = Array.from(
    new Map(cfg.registers.map(r => [r.address, r])).values()
  ).map(r =>
    `#define ${up}_REG_${cIdent(r.regName)}_OFFSET ${formatAddress(r.address)}U  /* ${r.regName} */`
  ).join('\n');

  // Per port: set (RMW with mask) and get
  const fns = cfg.registers.map(r => {
    const mask = ((1 << r.width) - 1);
    const maskHex = `0x${mask.toString(16).toUpperCase()}U`;
    const msb = r.msb, lsb = r.lsb;
    const out: string[] = [];
    if (r.mode !== 'RO') {
      out.push(
        `void ${cfg.ipName}_set_${r.mappedPort}(uint32_t value) {\n` +
        `    uint32_t word = ${cfg.ipName}_read(${formatAddress(r.address)}U);\n` +
        `    word &= ~(${maskHex} << ${lsb});\n` +
        `    word |= (value & ${maskHex}) << ${lsb};\n` +
        `    ${cfg.ipName}_write(${formatAddress(r.address)}U, word);\n` +
        `}\n`
      );
    }
    if (r.mode !== 'WO') {
      out.push(
        `uint32_t ${cfg.ipName}_get_${r.mappedPort}(void) {\n` +
        `    return (${cfg.ipName}_read(${formatAddress(r.address)}U) >> ${lsb}) & ${maskHex};\n` +
        `}\n`
      );
    }
    return `/* ${r.mappedPort} -> ${r.regName}[${r.msb}:${r.lsb}] (${r.width} bit, ${r.mode}) */\n${out.join('\n')}`;
  }).join('\n');

  return `/* ${cfg.ipName} — autogenerated C driver implementation. */
#include "${cfg.ipName}_driver.h"

${regConsts}

uint32_t ${cfg.ipName}_read(uint32_t offset) {
    return *(volatile uint32_t *)(${up}_BASE + offset);
}

void ${cfg.ipName}_write(uint32_t offset, uint32_t value) {
    *(volatile uint32_t *)(${up}_BASE + offset) = value;
}

${fns}
`;
}

