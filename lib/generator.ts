function verilogPortDecl(pc: PortConfig): string {
  const p = pc.port;
  const dir = p.direction === 'input' ? 'input  wire' :
              p.direction === 'output' ? 'output wire' : 'inout  wire';
  const sign = p.signed ? ' signed' : '';
  const width = p.width > 1 ? ` [${p.msb}:${p.lsb}]` : '';
  return `    ${dir}${sign}${width} ${p.name}`;
}

function externalPorts(portConfigs: PortConfig[], clock: ClockConfig | null, reset: ResetConfig | null): string {
  const lines: string[] = [];
  for (const pc of portConfigs) {
    const t = pc.portType;
    if (t === PortType.EXTERNAL_INPUT || t === PortType.EXTERNAL_OUTPUT || t === PortType.EXTERNAL_INOUT) {
      lines.push(verilogPortDecl(pc) + ',');
    }
    if (t === PortType.CLOCK && clock && !clock.useAxiClock) {
      lines.push(verilogPortDecl(pc) + ',');
    }
    if (t === PortType.RESET && reset && !reset.useAxiReset) {
      lines.push(verilogPortDecl(pc) + ',');
    }
  }
  return lines.join('\n');
}

function moduleInstantiation(cfg: IPConfig): string {
  const { portConfigs, registers, clock, reset } = cfg;
  // Derive the actual top module name from ipName (strip _axi suffix)
  const topModName = cfg.ipName.replace(/_axi$/i, '');
  const lines: string[] = [];
  lines.push(`    ${topModName} u_${topModName} (`);

  const mappings: string[] = [];
  for (const pc of portConfigs) {
    const p = pc.port;
    switch (pc.portType) {
      case PortType.CLOCK: {
        const sig = clock?.useAxiClock ? 'S_AXI_ACLK' : p.name;
        mappings.push(`        .${p.name}(${sig})`);
        break;
      }
      case PortType.RESET: {
        const sig = reset?.useAxiReset ? 'S_AXI_ARESETN' : p.name;
        mappings.push(`        .${p.name}(${sig})`);
        break;
      }
      case PortType.AXI_REGISTER: {
        const reg = registers.find(r => r.mappedPort === p.name);
        if (reg) {
          const slice = p.width < 32 ? `[${reg.msb}:${reg.lsb}]` : '';
          mappings.push(`        .${p.name}(${reg.regName}${slice})`);
        } else {
          mappings.push(`        .${p.name}(/* unassigned */)`);
        }
        break;
      }
      case PortType.EXTERNAL_INPUT:
      case PortType.EXTERNAL_OUTPUT:
      case PortType.EXTERNAL_INOUT:
        mappings.push(`        .${p.name}(${p.name})`);
        break;
      case PortType.IGNORE:
        break;
    }
  }
  lines.push(mappings.join(',\n'));
  lines.push('    );');
  return lines.join('\n');
}

