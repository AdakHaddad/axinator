    pc.portType === PortType.EXTERNAL_INOUT ||
    (pc.portType === PortType.CLOCK && cfg.clock && !cfg.clock.useAxiClock) ||
    (pc.portType === PortType.RESET && cfg.reset && !cfg.reset.useAxiReset)
