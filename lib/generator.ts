export function generateAll(cfg: IPConfig): GeneratedFiles {
  const sourceMap = new Map<string, string>();
  for (const f of cfg.sourceFiles) {
    sourceMap.set(f.filename, f.content);
  }

  return {
    topWrapper:    generateTopWrapper(cfg),
    axiSlave:      generateAxiSlave(cfg),
    sourceMap,
    registerMapMd: generateRegMapMd(cfg),
    componentXml:  generateComponentXml(cfg),
    readme:        generateReadme(cfg),
    driverHeader:  generateDriverHeader(cfg),
    driverSource:  generateDriverSource(cfg),
  };
}
